function isPlainObject(value) {
  return Boolean(value) && typeof value === 'object' && !Array.isArray(value);
}

function deepMerge(baseValue, overrideValue) {
  if (Array.isArray(overrideValue)) {
    return [...overrideValue];
  }

  if (!isPlainObject(baseValue) || !isPlainObject(overrideValue)) {
    return overrideValue ?? baseValue;
  }

  const mergedValue = { ...baseValue };
  Object.keys(overrideValue).forEach((key) => {
    mergedValue[key] = deepMerge(baseValue[key], overrideValue[key]);
  });
  return mergedValue;
}

export function getSiteCopy(language) {
  const baseCopy = SITE_COPY.en;
  if (!language || language === 'en' || !SITE_COPY[language]) {
    return baseCopy;
  }
  return deepMerge(baseCopy, SITE_COPY[language]);
}
